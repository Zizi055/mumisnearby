// ─────────────────────────────────────────────────────────────────────
// Редакция сборки: B2C или B2B.
//
// Одно приложение собирается дважды:
//
//   VITE_EDITION=b2c  →  rodnyegolosa.ru   (частные клиенты)
//   VITE_EDITION=b2b  →  rodnoygolos.ru    (корпоративные клиенты)
//
// Почему не отдельный репозиторий: кабинет сотрудника — это тот же
// кабинет пользователя (запись голоса, библиотека, плеер, генерация,
// профиль — ~35 тысяч строк), отличается он только отсутствием оплаты и
// активацией по промокоду. Форк означал бы, что каждый баг в плеере и
// каждая правка дизайна делаются дважды руками, и через месяц копии
// разъехались бы.
//
// Правило: НИКАКОЙ логики «если B2B, то чуть иначе» внутри компонентов.
// Редакция влияет только на состав — какие роуты смонтированы, какие
// пункты меню показаны, какие тарифы и тексты взяты. Поведение самих
// экранов одинаковое.
// ─────────────────────────────────────────────────────────────────────

const RAW = import.meta.env.VITE_EDITION;

export const EDITION = RAW === 'b2b' ? 'b2b' : 'b2c';

export const isB2B = EDITION === 'b2b';
export const isB2C = !isB2B;

// Название продукта в интерфейсе. На B2B-домене «Родной Голос» —
// единственное число, как в корпоративном ТЗ.
export const PRODUCT_NAME = isB2B ? 'Родной Голос' : 'Родные голоса';

// Адрес маркетингового сайта своей редакции: ЛК живёт на том же домене,
// поэтому достаточно относительных ссылок, но хлебные крошки и ссылка
// «на главную» должны вести на правильную страницу.
export const LANDING_URL = isB2B ? '/b2b.html' : '/index.html';
