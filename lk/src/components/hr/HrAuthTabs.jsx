import { NavLink } from 'react-router-dom';

// ─────────────────────────────────────────────────────────────────────
// Переключатель «Вход / Регистрация» на корпоративных экранах входа.
//
// Раньше это были две отдельные страницы, связанные строкой мелким
// шрифтом под кнопкой. Человек, впервые пришедший с лендинга, попадал
// на форму входа и не понимал, что делать: логина у него ещё нет, а
// путь к регистрации выглядел как сноска.
//
// Это именно ссылки, а не состояние компонента: адрес остаётся
// осмысленным, кнопки с лендинга ведут сразу на нужную вкладку, и
// «назад» в браузере работает как ожидается.
// ─────────────────────────────────────────────────────────────────────

export default function HrAuthTabs() {
  return (
    <div className="lk-hr-tabs" role="tablist">
      <NavLink
        to="/hr/login"
        role="tab"
        className={({ isActive }) => `lk-hr-tabs__item ${isActive ? 'is-active' : ''}`}
      >
        Вход
      </NavLink>

      <NavLink
        to="/hr/register"
        role="tab"
        className={({ isActive }) => `lk-hr-tabs__item ${isActive ? 'is-active' : ''}`}
      >
        Регистрация
      </NavLink>
    </div>
  );
}
