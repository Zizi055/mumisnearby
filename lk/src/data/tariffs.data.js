function liveList(pick) {
  return new Proxy([], {
    get(_target, prop) {
      const list = pick();
      if (prop === Symbol.iterator) return list[Symbol.iterator].bind(list);
      const value = list[prop];
      return typeof value === 'function' ? value.bind(list) : value;
    },
  });
}

